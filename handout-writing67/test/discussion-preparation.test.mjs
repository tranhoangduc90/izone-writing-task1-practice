import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile,mkdtemp,writeFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {PGlite} from '@electric-sql/pglite';
import {createStore} from '../src/store.mjs';
import {createService} from '../src/service.mjs';
import {promptRenderer} from '../src/prompt.mjs';
import {dashboardProjection} from '../src/dashboard.mjs';
import {LEGACY_LESSON5} from '../src/lessons.mjs';

test('Lesson 15 checks five inputs and resumes an old draft without requiring the retired fields',async t=>{
 const db=new PGlite();
 const dir=await mkdtemp(join(tmpdir(),'h67-discussion-'));
 t.after(async()=>{await db.close();await rm(dir,{recursive:true,force:true});});
 for(const file of ['001-initial.sql','002-activity-log.sql'])await db.exec(await readFile(new URL('../db/'+file,import.meta.url),'utf8'));
 const read=async path=>JSON.parse(await readFile(new URL('../'+path,import.meta.url),'utf8'));
 const definition=await read('lesson-definitions/lesson15.json');
 const entry={...await read('lesson-rubrics/lesson15.json'),definition};
 const legacy={definition:{...LEGACY_LESSON5,classes:['IC2213']},version:'lesson5-rubric-v3',rubrics:Object.fromEntries(['topic','b1','b2','a','x','vocab'].map(k=>[k,'Fixture '+k]))};
 const registry=join(dir,'registry.json');await writeFile(registry,JSON.stringify({version:'handout67-lessons-v1',lessons:{lesson5:legacy,lesson15:entry}}));
 const render=await promptRenderer(registry);
 const store=createStore(db);
 const service=createService({store,roster:async()=>[{classRef:'IC2213',students:[{studentRef:'new'},{studentRef:'old'}]}],secret:'s'.repeat(40),lessons:render.lessons,renderJob:render});
 const identity={activity:'lesson15',classRef:'IC2213'};
 const fresh=await service.open({...identity,studentRef:'new'});
 assert.equal(Object.keys(fresh.session.responses).length,19);
 for(const field of ['agreementLevel','positionLimit'])assert.ok(!Object.hasOwn(fresh.session.responses,field));
 const opened=await service.open({...identity,studentRef:'old'}),ref=opened.session.ref;
 await store.edit(ref,s=>{
  s.preparationKind='opinion-v1';
  s.responses.agreementLevel='Đồng ý một phần';
  s.responses.positionLimit='Bản cũ giữ nguyên';
  s.responses.body2_topicSentence='Bản nháp câu chủ đề';
 });
 const ideas={chosenSolution:definition.solutionOptions[1],body1_idea1:'Cách ly người nguy hiểm',body1_idea2:'Giam cả người phạm lỗi nhẹ gây quá tải',body2_idea1:'Lao động công ích có giám sát',body2_idea2:'Bồi thường thiệt hại'};
 const resumed=await service.open({...identity,studentRef:'old'});
 assert.equal(resumed.session.preparationKind,'discussion-v1');
 assert.equal(resumed.session.responses.body2_topicSentence,'Bản nháp câu chủ đề');
 const saved=await service.save(ref,resumed.token,{baseVersion:resumed.session.version,requestId:crypto.randomUUID(),responses:ideas});
 await service.check(ref,resumed.token,{baseVersion:saved.version,requestId:crypto.randomUUID(),section:'outline',bodyIndex:0});
 const [job]=await service.claim();
 const prompt=render(job);
 const input=JSON.parse(prompt.split('\n').at(-1));
 assert.equal(input.purpose,'DISCUSS_BOTH_VIEWS_AND_GIVE_OPINION');
 assert.deepEqual(input.content,ideas);
 assert.equal(dashboardProjection(await store.read(ref)).totalFields,19);
 await service.complete({...job,result:{resultStatus:'passed',feedback:'Đã trình bày đủ hai quan điểm.'}});
 const after=await service.read(ref,resumed.token);
 assert.equal(after.steps.outline.status,'passed');
 assert.equal(after.responses.positionLimit,'Bản cũ giữ nguyên');
 assert.equal(after.responses.body2_topicSentence,'Bản nháp câu chủ đề');
});
