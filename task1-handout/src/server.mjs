import {createDatabasePool} from '../vendor/db.js';
import {createSharedTeacherVerifier} from '../vendor/teacher-sso/consumer.js';
import {loadConfig} from './config.mjs';
import {createService} from './service.mjs';
import {createApp} from './app.mjs';
import {createHistory} from './history.mjs';
import {createAuthority} from './authority.mjs';
import {Pool} from 'pg';
import {z} from 'zod';
import {loadSwRoster} from '../vendor/sw-roster-runtime.mjs';
const config=loadConfig(),pool=createDatabasePool(config),service=createService({pool,pepper:config.pepper,history:createHistory({pool})});
const verifyTeacher=config.ssoUrl?createSharedTeacherVerifier({url:config.ssoUrl,key:config.ssoKey}):null;
const authority=createAuthority(config.authorityUrl,pool);
const swRoster=await loadSwRoster({z,Pool,pool,product:'task1',origins:config.origins});
const app=createApp({config,pool,service,verifyTeacher,authority,swRoster});
const server=app.listen(config.port,'0.0.0.0',()=>console.log('SW Task 1 API ready'));
swRoster?.start();
server.requestTimeout=30000;server.headersTimeout=31000;
for(const signal of ['SIGTERM','SIGINT'])process.on(signal,()=>{server.close(async()=>{await swRoster?.close();await pool.end();process.exit(0);});setTimeout(()=>process.exit(1),10000).unref();});
